LibraryData *ACompiler::requestImport(LibraryData *currentLibrary,
                                      const char *path) {
	{
		auto it = builtInLibrariesMap.find(std::string(path));
		if (it != builtInLibrariesMap.end()) {
			return builtInLibraries[it->second].get();
		}
	}

#ifdef __EMSCRIPTEN__
	return nullptr;
#else
	std::filesystem::path input = path;
	std::filesystem::path currentPath;
	if (currentLibrary && (currentLibrary->flags & LibraryFlags::IS_FILE)) {
		currentPath = std::filesystem::path(currentLibrary->path).parent_path();
	} else {
		currentPath = std::filesystem::current_path();
	}
	std::filesystem::path resolved = (currentPath / input).lexically_normal();
	if (!std::filesystem::exists(resolved)) {
		if (mainSource && (mainSource->flags & LibraryFlags::IS_FILE)) {
			std::filesystem::path mainPath =
			    std::filesystem::path(mainSource->path).parent_path();
			std::filesystem::path mainResolved =
			    (mainPath / input).lexically_normal();
			if (std::filesystem::exists(mainResolved)) {
				resolved = mainResolved;
			} else {
				return nullptr;
			}
		} else {
			return nullptr;
		}
	}
	std::string libPath = resolved.string();
	// std::cerr << libPath << "\n";
	{
		auto it = generatedLibraryMap.find(libPath);
		if (it != generatedLibraryMap.end()) {
			return generatedLibraries[it->second].get();
		}
	}
	// std::cerr << "START    " << input << "\n"
	//           << currentPath << "\n"
	//           << resolved << "\n";
	auto library = std::make_unique<LibraryData>(
	    libPath, 0,
	    currentLibrary ? currentLibrary->nativeFuncMap : EMPTY_NATIVE_MAP);
	LibraryData *libPtr = library.get();
	generatedLibraryMap[libPath] = generatedLibraries.size();
	generatedLibraries.push_back(std::move(library));
	if (currentLibrary) {
		libPtr->flags = currentLibrary->flags;
	}
	Lexer::loadFile(&parserContext, libPtr);
	return libPtr;
#endif
}

void ACompiler::lexerTextToToken(LibraryData *library) {
	switch (state) {
		case CompilerState::CT_BYTECODE_READY:
			throw std::logic_error("Bytecode already generated. Call run() to "
			                       "execute or refresh() to register.");
			break;
		case CompilerState::CT_ERROR:
			throw std::logic_error("Compiler is in ERROR state. Call refresh() "
			                       "before register source.");
		default:
			break;
	}
	auto &context = parserContext;
	auto &compile = vm.data;

	loadSource(library);
	library->rawData.clear();
}

void ACompiler::loadSource(LibraryData *library) {
	auto &context = parserContext;
	auto &compile = vm.data;
	std::vector<Offset> importOffset;
	lexerData(in_data, *this, library, &importOffset);
	// for (auto& token : lexerContext.tokens) {
	// 	std::cerr<<token.toString(context)<<" ";
	// }
	// std::cerr<<"h "<<source.mode.path<<": "<<source.end<<"\n";
	if (library->lexerContext.hasError) {
		state = CompilerState::CT_ERROR;
		return;
	}
	try {
		for (auto &pos : importOffset) {
			auto lib =
			    loadImport(in_data, library, library->lexerContext.tokens,
			               *this, (size_t)pos);
			for (auto &[key, l] : lib->dependencies) {
				library->dependencies[key] = l;
			}
			library->dependencies[lib->path] = lib;
		}
		state = CompilerState::CT_ANALYZED;
	} catch (const ParserError &err) {
		context.logError(err.line, err.message, err.hint);
		state = CompilerState::CT_ERROR;
	}
}

LibraryData *
ACompiler::registerBuiltInLibrary(const char *path, LibraryConfig config,
                                  const ANativeMap &nativeFuncMap) {
	if (loadedBuiltIn) {
		throw std::logic_error("Cannot register built-in library: Compiler has "
		                       "already analyzed or generated bytecodes.");
	}
	uint32_t flags = LibraryFlags::IS_BUILT_IN;
	if (config.autoImport) {
		flags |= LibraryFlags::AUTO_IMPORT;
	}
	if (config.allowLateinitKeyword) {
		flags |= LibraryFlags::ALLOW_LATEINIT_KEYWORD;
	}
	if (config.allowNonNullAssertion) {
		flags |= LibraryFlags::ALLOW_NON_NULL_ASSERTION;
	}
	uint32_t libraryOffset = builtInLibraries.size();
	auto lib = std::make_unique<LibraryData>(path, flags, nativeFuncMap);
	LibraryData *libPtr = lib.get();
	builtInLibraries.push_back(std::move(lib));
	builtInLibrariesMap[path] = libraryOffset;
	Lexer::loadFile(&parserContext, libPtr);
	if (config.autoImport) {
		autoImportMap[path] = libPtr;
	}
	return libPtr;
}

LibraryData *
ACompiler::registerBuiltInLibrary(const char *path, const char *data,
                                  LibraryConfig config,
                                  const ANativeMap &nativeFuncMap) {
	if (loadedBuiltIn) {
		throw std::logic_error("Cannot register built-in library: Compiler has "
		                       "already analyzed or generated bytecodes.");
	}
	uint32_t flags = LibraryFlags::IS_BUILT_IN;
	if (config.autoImport) {
		flags |= LibraryFlags::AUTO_IMPORT;
	}
	if (config.allowLateinitKeyword) {
		flags |= LibraryFlags::ALLOW_LATEINIT_KEYWORD;
	}
	if (config.allowNonNullAssertion) {
		flags |= LibraryFlags::ALLOW_NON_NULL_ASSERTION;
	}
	uint32_t libraryOffset = builtInLibraries.size();
	auto lib = std::make_unique<LibraryData>(path, flags, nativeFuncMap);
	LibraryData *libPtr = lib.get();
	libPtr->rawData = data;
	builtInLibraries.push_back(std::move(lib));
	builtInLibrariesMap[path] = libraryOffset;
	if (config.autoImport) {
		autoImportMap[path] = libPtr;
	}
	return libPtr;
}

void ACompiler::loadBuiltInFunctions() {
	AUTOLANG_PROFILE_MARK("Compile: Load Built-in Stdlib Start");
	for (auto &library : builtInLibraries) {
		if (!library->lexerContext.tokens.empty())
			continue;
		lexerTextToToken(library.get());
		library->lexerContext.bracketStack.clear();
		library->lexerContext.bracketStack.shrink_to_fit();
	}
	parserContext.importMap.clear();
	loadedBuiltIn = true;
	parserContext.stdLexerString = parserContext.lexerString;
	parserContext.stdLexerStringMap = parserContext.lexerStringMap;
	AUTOLANG_PROFILE_MARK("Compile: Built-in Stdlib Done");
}

void ACompiler::loadMainSource(const char *path, LibraryConfig config,
                               const ANativeMap &nativeFuncMap) {
	if (!loadedBuiltIn) {
		loadBuiltInFunctions();
	}
	if (!path || !path[0]) {
		throw std::runtime_error("File path cannot be empty.");
	}
	LibraryData *library = requestImport(nullptr, path);
	if (!library) {
		throw std::runtime_error(
		    "File '" + std::string(path) +
		    "' does not exist\nHint: Check file path spelling and ensure the "
		    "file exists at specified relative path.");
	}
	parserContext.importMap[library->path] = library;
	library->nativeFuncMap = nativeFuncMap;
	if (config.allowLateinitKeyword) {
		library->flags |= LibraryFlags::ALLOW_LATEINIT_KEYWORD;
	}
	if (config.allowNonNullAssertion) {
		library->flags |= LibraryFlags::ALLOW_NON_NULL_ASSERTION;
	}
	loadMainSource(library);
}

void ACompiler::loadMainSource(const char *path, const char *data,
                               LibraryConfig config,
                               const ANativeMap &nativeFuncMap) {
	if (!loadedBuiltIn) {
		loadBuiltInFunctions();
	}
	auto library = std::make_unique<LibraryData>(path, 0, nativeFuncMap);
	LibraryData *libPtr = library.get();
	parserContext.importMap[path] = libPtr;
	libPtr->rawData = data;
	generatedLibraryMap[path] = generatedLibraries.size();
	generatedLibraries.push_back(std::move(library));
	if (config.allowLateinitKeyword) {
		libPtr->flags |= LibraryFlags::ALLOW_LATEINIT_KEYWORD;
	}
	if (config.allowNonNullAssertion) {
		libPtr->flags |= LibraryFlags::ALLOW_NON_NULL_ASSERTION;
	}
	loadMainSource(libPtr);
}

void ACompiler::loadMainSource(LibraryData *library) {
	auto &context = parserContext;
	auto &compile = vm.data;

	mainSource = library;

	std::string autoImportStr;
	for (auto &[k, lib] : autoImportMap) {
		autoImportStr += "@import(\"" + lib->path + "\")";
		// library->dependencies[k] = lib;
		// library->lexerContext.tokens.insert(
		//     library->lexerContext.tokens.begin(),
		//     lib->lexerContext.tokens.begin(),
		//     lib->lexerContext.tokens.end());
		// for (auto &[key, l] : lib->dependencies) {
		// 	library->dependencies[key] = l;
		// }
	}
	library->rawData = autoImportStr + library->rawData;

	AUTOLANG_PROFILE_MARK("Compile: Main Source Lexer Start");
	std::vector<Offset> importOffset;
	lexerData(in_data, *this, library, &importOffset);
	library->rawData.clear();

	if (mainSource->lexerContext.hasError) {
		state = CompilerState::CT_ERROR;
		return;
	}

	library->lexerContext.tokens.pop_back();

	try {
		for (auto &pos : importOffset) {
			auto lib =
			    loadImport(in_data, library, library->lexerContext.tokens,
			               *this, (size_t)pos);
			for (auto &[key, l] : lib->dependencies) {
				library->dependencies[key] = l;
			}
			library->dependencies[lib->path] = lib;
		}
	} catch (const ParserError &err) {
		context.logError(err.line, err.message, err.hint);
		state = CompilerState::CT_ERROR;
		context.currentClassId = std::nullopt;
		context.currentFunctionId = context.mainFunctionId;
		return;
	}
	AUTOLANG_PROFILE_MARK("Compile: Main & Imports Tokenized");

	auto &newEstimate = mainSource->lexerContext.estimate;

	for (auto &[name, lib] : library->dependencies) {
		const auto &libEstimate = lib->lexerContext.estimate;

		newEstimate.declaration += libEstimate.declaration;
		newEstimate.classes += libEstimate.classes;
		newEstimate.functions += libEstimate.functions;
		newEstimate.constructorNode += libEstimate.constructorNode;
		// newEstimate.ifNode += libEstimate.ifNode;
		// newEstimate.whileNode += libEstimate.whileNode;
		// newEstimate.returnNode += libEstimate.returnNode;
		// newEstimate.setNode += libEstimate.setNode;
		// newEstimate.binaryNode += libEstimate.binaryNode;
		// newEstimate.tryCatchNode += libEstimate.tryCatchNode;
		// newEstimate.throwNode += libEstimate.throwNode;
	}

	context.mode = library;
	context.tokens = mainSource->lexerContext.tokens;
	context.mainLexerContext = &library->lexerContext;
	context.loadingLibs.reserve(8);
	context.loadingLibs.push_back(library);
	loadedMainSource = true;
	state = CompilerState::CT_ANALYZED;
}

bool ACompiler::compileAndRun(const char *path, LibraryConfig config,
                              const ANativeMap &nativeFuncMap) {
	try {
		if (!compile(path, config, nativeFuncMap))
			return false;
		run();
		return true;
	} catch (const std::exception &e) {
		std::cerr << e.what() << "\n";
	}
	return false;
}

bool ACompiler::compileAndRun(const char *path, const char *data,
                              LibraryConfig config,
                              const ANativeMap &nativeFuncMap) {
	try {
		if (!compile(path, data, config, nativeFuncMap))
			return false;
		run();
		return true;
	} catch (const std::exception &e) {
		std::cerr << e.what() << "\n";
	}
	return false;
}

bool ACompiler::compile(const char *path, LibraryConfig config,
                        const ANativeMap &nativeFuncMap) {
	if (shouldRefresh || hasError()) {
		refresh();
	}
	shouldRefresh = true;
	loadMainSource(path, config, nativeFuncMap);
	if (hasError()) {
		return false;
	}
	generateBytecodes();
	if (hasError()) {
		return false;
	}
	return true;
}

bool ACompiler::compile(const char *path, const char *data,
                        LibraryConfig config, const ANativeMap &nativeFuncMap) {
	if (shouldRefresh || hasError()) {
		refresh();
	}
	shouldRefresh = true;
	loadMainSource(path, data, config, nativeFuncMap);
	if (hasError()) {
		return false;
	}
	generateBytecodes();
	if (hasError()) {
		return false;
	}
	return true;
}

void ACompiler::generateBytecodes() {
	switch (state) {
		case CompilerState::CT_BYTECODE_READY:
			throw std::logic_error("Bytecode already generated. Call run() to "
			                       "execute instead of generating again.");
			break;
		case CompilerState::CT_ERROR:
			throw std::logic_error("Compiler is in ERROR state. Call refresh() "
			                       "before generate bytecode.");
		case CompilerState::CT_READY:
			throw std::logic_error(
			    "No bytecode generated. Compile source before generating.");
		default:
			break;
	}

	if (!loadedMainSource) {
		throw std::logic_error(
		    "No main source generated. Compile main source before generating.");
	}

	auto &context = parserContext;
	auto &compile = vm.data;

	estimate(in_data, mainSource->lexerContext);
	// long long line = context.tokens.empty() ? 0 : context.tokens[0].line;
	// for (auto& token : context.tokens) {
	// 	if(line != token.line) {
	// 		std::cerr<<"\n";
	// 		line = token.line;
	// 	}
	// 	std::cerr<<token.toString(context)<<" ";
	// }
	// std::cerr<<"\n";

	AUTOLANG_PROFILE_MARK("Compile: AST Construction Start");
	context.currentAllOpcodeLine = &compile.allOpcodeLines;
	context.currentTokenPos = 0;
	size_t &i = context.currentTokenPos;
	while (i < context.tokens.size()) {
		try {
			auto node = loadLine(in_data, i);
			ensureEndline(in_data, i);
			++i;
			if (node == nullptr) {
				continue;
			}
			// if (context.annotationFlags || context.modifierflags) {
			// 	throw ParserError(node->line, "Bug: Annotations and modifiers
			// hasn't reset yet");
			// }
			context.getCurrentFunctionInfo(in_data)->body.nodes.push_back(node);
		} catch (const std::runtime_error &err) {
			context.hasError = true;
			std::cerr << "Unexpected exception: " << err.what() << '\n';
		} catch (const ParserError &err) {
			context.hasError = true;
			context.logError(err.line, err.message, err.hint);
			if (i >= context.tokens.size())
				break;
			uint32_t line = context.tokens[i].line;
			Lexer::Token *token;
			int32_t countScope = 0;
			while (nextTokenSameLine(&token, context.tokens, i, line)) {
				switch (token->type) {
					case Lexer::TokenType::LBRACE: {
						++countScope;
						break;
					}
					case Lexer::TokenType::RBRACE: {
						--countScope;
						break;
					}
				}
			}
			if (countScope >= 1) {
				while (nextToken(&token, context.tokens, i)) {
					switch (token->type) {
						case Lexer::TokenType::LBRACE: {
							++countScope;
							break;
						}
						case Lexer::TokenType::RBRACE: {
							--countScope;
							if (countScope == 0) {
								nextToken(&token, context.tokens, i);
								goto finishedCatch;
							}
							break;
						}
					}
				}
			}
		finishedCatch:;
		}
	}
	// auto parserTime = std::chrono::high_resolution_clock::now();
	// std::cerr << "Generated node : "
	//           << std::chrono::duration_cast<std::chrono::milliseconds>(
	//                  parserTime - startParserTime)
	//                  .count()
	//           << " ms" << '\n';

	if (context.hasError) {
		state = CompilerState::CT_ERROR;
		return;
	}

	AUTOLANG_PROFILE_MARK("Compile: AST Nodes Created");

	{
		LexerStringId mainNameId = context.createLexerStringIfNotExists("main");
		auto mainIt = compile.funcMap.find("main");
		if (mainIt != compile.funcMap.end() && !mainIt->second.empty()) {
			auto mainFuncInfo = context.getMainFunctionInfo(in_data);
			bool alreadyHasMainCall = false;
			for (auto *stmt : mainFuncInfo->body.nodes) {
				if (stmt && stmt->kind == NodeType::CALL) {
					auto callStmt = static_cast<CallNode *>(stmt);
					if (callStmt->nameId == mainNameId) {
						alreadyHasMainCall = true;
						break;
					}
				}
			}
			if (!alreadyHasMainCall) {
				auto callMainNode = context.callNodePool.push(
				    1, 0, std::nullopt, nullptr, mainNameId,
				    std::vector<HasClassIdNode *>(), false, false, false);
				mainFuncInfo->body.nodes.push_back(callMainNode);
			}
		}
	}

	try {
		printDebug("-----------------AST Node-----------------\n");

		printDebug("Load all generic call");
		for (auto *declaration : context.genericCallers) {
			declaration->template load<true, true>(in_data);
		}

		printDebug("Load all class declarations");
		// Load class declaration (generics as T won't have class id)
		for (auto *declaration : context.allClassDeclarations) {
			declaration->template load<true>(in_data);
		}

		printDebug("Start optimize classes");
		size_t sizeNewClasses = context.newClasses.getSize();
		for (size_t i = 0; i < sizeNewClasses; ++i) {
			context.newClasses[i]->optimize(in_data);
			// auto classInfo =
			// context.classInfo[context.newClasses[i]->classId];
		}

		printDebug("Start optimize declaration nodes in functions");
		for (int i = 0; i < context.declarationNodePool.index; ++i) {
			context.declarationNodePool.objects[i].optimize(in_data);
		}
		for (auto *node : context.declarationNodePool.vecs) {
			node->optimize(in_data);
		}

		printDebug("Start optimize constructor nodes");
		for (int i = 0; i < sizeNewClasses; ++i) {
			auto *node = context.newClasses[i];
			auto clazz = compile.classes[node->classId];
			auto classInfo = context.classInfo[clazz->id];
			if (classInfo->genericData)
				continue;
			if (classInfo->primaryConstructor) {
				classInfo->primaryConstructor->optimize(in_data);
			} else {
				for (auto *constructor : classInfo->secondaryConstructor) {
					constructor->optimize(in_data);
				}
			}
		}
		printDebug("Start optimize functions");
		size_t sizeNewFunctions = context.newFunctions.getSize();
		for (int i = 0; i < sizeNewFunctions; ++i) {
			auto *createFunctionNode = context.newFunctions[i];
			auto funcInfo = context.functionInfo[createFunctionNode->id];
			if ((createFunctionNode->functionFlags &
			     FunctionFlags::FUNC_SKIP_LOAD) ||
			    createFunctionNode->optimized) {
				continue;
			}
			if (createFunctionNode->contextCallClassId) {
				auto classInfo =
				    context.classInfo[*createFunctionNode->contextCallClassId];
				if (classInfo->genericData)
					continue;
			}
			createFunctionNode->optimize(in_data);
		}

		printDebug("Start load virtual");
		for (size_t i = 0; i < sizeNewClasses; ++i) {
			auto *newClass = context.newClasses[i];
			auto classInfo = context.classInfo[newClass->classId];
			if (classInfo->genericData)
				continue;
			newClass->loadSuper(in_data);
		}

		printDebug("Validate generic declaration condition");
		for (auto &[declaration, vec] : context.checkValidateExtends) {
			ClassId conditionClassId =
			    *(*declaration->condition).classDeclaration->classId;
			for (auto *inputClass : vec) {
				ClassId inputClassId = *inputClass->classId;
				if (!compile.classes[inputClassId]->inheritance.get(
				        conditionClassId) &&
				    inputClassId != conditionClassId) {
					throw ParserError(
					    declaration->line,
					    "Type constraint violation: generic argument '" +
					        compile.classes[inputClassId]->getName(compile) +
					        "' does not extend required base class '" +
					        compile.classes[conditionClassId]->getName(
					            compile) +
					        "'", "Generic argument type must implement or "
					        "inherit the constraint type.");
				}
			}
		}

		printDebug("Start optimize parameter default value");
		for (auto parameters : context.defaultValueParameter) {
			for (auto &parameter : parameters->parameterDefaultValues) {
				parameter =
				    static_cast<HasClassIdNode *>(parameter->resolve(in_data));
				parameter =
				    static_cast<HasClassIdNode *>(parameter->optimize(in_data));
			}
		}

		printDebug("Start optimize detach member default value");
		for (size_t i = 0; i < sizeNewClasses; ++i) {
			auto *newClass = context.newClasses[i];
			auto classInfo = context.classInfo[newClass->classId];
			if (classInfo->genericData)
				continue;
			newClass->body.resolve(in_data);
			newClass->body.optimize(in_data);
		}

		printDebug("Start optimize static nodes");
		for (auto &node : context.staticNode) {
			ParserContext::mode = node->mode;
			node = node->resolve(in_data);
			node = node->optimize(in_data);
		}

		printDebug("Start put bytecodes constructor");
		HashSet<FunctionId> emittedConstructors;
		auto emitConstructors = [&]() {
			for (size_t i = 0; i < context.newClasses.getSize(); ++i) {
				auto *node = context.newClasses[i];
				auto classInfo =
				    context.classInfo[compile.classes[node->classId]->id];
				if (classInfo->genericData)
					continue;
				if (classInfo->primaryConstructor) {
					// Put initial bytecodes, example val a = 5 => SetNode
					//  node->body.optimize(in_data);
					auto func =
					    compile.functions[classInfo->primaryConstructor->funcId];
					if (emittedConstructors.count(func->id))
						continue;
					emittedConstructors.insert(func->id);
					context.currentBytecodePos = compile.allBytecodes.size();
					context.currentOpcodeIndex = compile.allOpcodeLines.size();
					func->bytecodes.offset = context.currentBytecodePos;
					func->opcodeIndex = context.currentOpcodeIndex;
					context.currentClassId = node->classId;
					node->body.resolve(in_data);
					node->body.optimize(in_data);
					context.currentFunctionId = func->id;
					node->body.putBytecodes(in_data, compile.allBytecodes);
					node->body.rewrite(in_data, compile.allBytecodes.data() +
					                                context.currentBytecodePos);

					classInfo->primaryConstructor->body.resolve(in_data);
					classInfo->primaryConstructor->body.optimize(in_data);
					classInfo->primaryConstructor->body.putBytecodes(
					    in_data, compile.allBytecodes);
					classInfo->primaryConstructor->body.rewrite(
					    in_data,
					    compile.allBytecodes.data() + context.currentBytecodePos);

					func->bytecodes.size =
					    compile.allBytecodes.size() - func->bytecodes.offset;
					func->opcodeLineCount =
					    compile.allOpcodeLines.size() - func->opcodeIndex;
				} else {
					for (auto &constructor : classInfo->secondaryConstructor) {
						auto func = compile.functions[constructor->funcId];
						if (emittedConstructors.count(func->id))
							continue;
						emittedConstructors.insert(func->id);
						context.currentBytecodePos = compile.allBytecodes.size();
						context.currentOpcodeIndex = compile.allOpcodeLines.size();
						func->bytecodes.offset = context.currentBytecodePos;
						func->opcodeIndex = context.currentOpcodeIndex;

						// Put initial bytecodes, example val a = 5 => SetNode a
						// and value 5
						context.currentClassId = node->classId;
						context.currentFunctionId = func->id;
						node->body.resolve(in_data);
						node->body.optimize(in_data);
						node->body.putBytecodes(in_data, compile.allBytecodes);
						node->body.rewrite(in_data, compile.allBytecodes.data() +
						                                context.currentBytecodePos);
						// Put constructor bytecodes
						constructor->body.resolve(in_data);
						constructor->body.optimize(in_data);
						constructor->body.putBytecodes(in_data,
						                               compile.allBytecodes);
						constructor->body.rewrite(in_data,
						                          compile.allBytecodes.data() +
						                              context.currentBytecodePos);

						func->bytecodes.size =
						    compile.allBytecodes.size() - func->bytecodes.offset;
						func->opcodeLineCount =
						    compile.allOpcodeLines.size() - func->opcodeIndex;
					}
				}
				context.currentClassId = std::nullopt;
			}
		};
		emitConstructors();

		std::vector<uint8_t> mainFunctionBytecodes;
		std::vector<OpcodeLine> mainOpcodeLine;

		context.currentAllOpcodeLine = &mainOpcodeLine;

		printDebug("Start put bytecodes static nodes");
		context.currentBytecodePos = 0;
		context.currentOpcodeIndex = 0;
		context.currentFunctionId = context.mainFunctionId;
		for (auto &node : context.staticNode) {
			node->putBytecodes(in_data, mainFunctionBytecodes);
			node->rewrite(in_data, mainFunctionBytecodes.data());
		}

		printDebug("Inference function type");
		for (FunctionId id : context.mustInferenceFunctionType) {
			auto *funcInfo = context.functionInfo[id];
			if (funcInfo->genericData) {
				continue;
			}
			if (!funcInfo->inferenceNode->loaded) {
				auto lastFuncId = context.currentFunctionId;
				auto lastClassId = context.currentClassId;
				context.gotoFunction(id);
				if (funcInfo->clazz) {
					context.currentClassId = funcInfo->clazz->id;
				}
				funcInfo->inferenceNode->resolve(in_data);
				funcInfo->inferenceNode->optimize(in_data);
				funcInfo->inferenceNode->loaded = true;
				if (funcInfo->inferenceNode->value->classId ==
				    DefaultClass::voidClassId) {
					funcInfo->body.nodes[0] = funcInfo->inferenceNode->value;
				}
				context.gotoFunction(lastFuncId);
				context.currentClassId = lastClassId;
			}
		}

		printDebug("Start optimize bytecodes in main");
		auto mainFunc = context.getMainFunction(in_data);
		auto mainFuncInfo = context.getMainFunctionInfo(in_data);
		mainFunc->path = mainSource->path.c_str();
		for (auto *&node : mainFuncInfo->body.nodes) {
			ParserContext::mode = node->mode;
			node = node->resolve(in_data);
		}
		context.currentAllOpcodeLine = &compile.allOpcodeLines;
		mainFuncInfo->body.optimize(in_data);
		printDebug("Start put bytecodes in functions");
		for (size_t i = 0; i < context.newFunctions.getSize(); ++i) {
			auto *node = context.newFunctions[i];
			if (node->contextCallClassId) {
				auto classInfo = context.classInfo[*node->contextCallClassId];
				if (classInfo->genericData)
					continue;
			}
			auto func = compile.functions[node->id];
			auto funcInfo = context.functionInfo[node->id];
			if (func->functionFlags & FunctionFlags::FUNC_SKIP_LOAD) {
				continue;
			}
			if ((func->functionFlags & FunctionFlags::FUNC_OVERRIDE) &&
			    !(func->functionFlags & FunctionFlags::FUNC_IS_VIRTUAL)) {
				throw ParserError(
				    node->line,
				    "Function " +
				        context.functionInfo[node->id]->toString(in_data) +
				        " is marked @override but no virtual function was "
				        "found in superclass", "Check method name and "
				        "signature, and ensure base class method is marked "
				        "virtual.");
			}
			if (func->functionFlags & FunctionFlags::FUNC_IS_NATIVE)
				continue;
			context.currentFunctionId = func->id;
			context.currentClassId = node->contextCallClassId;
			if (!funcInfo->inferenceNode) {
				funcInfo->body.resolve(in_data);
				funcInfo->body.optimize(in_data);
			} else if (!funcInfo->inferenceNode->loaded) {
				funcInfo->inferenceNode->resolve(in_data);
				funcInfo->inferenceNode->optimize(in_data);
				funcInfo->inferenceNode->loaded = true;
				if (funcInfo->inferenceNode->value->classId ==
				    DefaultClass::voidClassId) {
					funcInfo->body.nodes[0] = funcInfo->inferenceNode->value;
				}
			}
			context.currentBytecodePos = compile.allBytecodes.size();
			context.currentOpcodeIndex = compile.allOpcodeLines.size();
			func->bytecodes.offset = context.currentBytecodePos;
			func->opcodeIndex = context.currentOpcodeIndex;
			funcInfo->body.putBytecodes(in_data, compile.allBytecodes);
			funcInfo->body.rewrite(in_data, compile.allBytecodes.data() +
			                                    context.currentBytecodePos);
			func->bytecodes.size =
			    compile.allBytecodes.size() - func->bytecodes.offset;
			func->opcodeLineCount =
			    compile.allOpcodeLines.size() - func->opcodeIndex;
			context.currentClassId = std::nullopt;
		}

		emitConstructors();

		printDebug("Start put bytecodes in main");
		context.currentBytecodePos = compile.allBytecodes.size();
		context.currentOpcodeIndex = compile.allOpcodeLines.size();
		mainFunc->bytecodes.offset = context.currentBytecodePos;
		compile.allBytecodes.insert(compile.allBytecodes.end(),
		                            mainFunctionBytecodes.begin(),
		                            mainFunctionBytecodes.end());
		compile.allOpcodeLines.insert(compile.allOpcodeLines.end(),
		                              mainOpcodeLine.begin(),
		                              mainOpcodeLine.end());
		context.currentFunctionId = context.mainFunctionId;
		mainFuncInfo->body.putBytecodes(in_data, compile.allBytecodes);
		mainFuncInfo->body.rewrite(in_data, compile.allBytecodes.data() +
		                                        context.currentBytecodePos);
		mainFunc->bytecodes.size =
		    compile.allBytecodes.size() - mainFunc->bytecodes.offset;
		mainFunc->opcodeLineCount =
		    compile.allOpcodeLines.size() - mainFunc->opcodeIndex;

		printDebug("Start put closure's bytecode on vector allBytecodes");
		for (auto closure : context.allClosureNode) {
			auto func = compile.functions[*closure->funcId];
			func->bytecodes.offset = compile.allBytecodes.size();
			func->opcodeIndex = compile.allOpcodeLines.size();
			func->bytecodes.size = closure->currentBytecodes.size();
			compile.allBytecodes.insert(compile.allBytecodes.end(),
			                            closure->currentBytecodes.begin(),
			                            closure->currentBytecodes.end());
			compile.allOpcodeLines.insert(compile.allOpcodeLines.end(),
			                              closure->currentOpcodeLine.begin(),
			                              closure->currentOpcodeLine.end());
			func->opcodeLineCount = closure->currentOpcodeLine.size();
		}

		printDebug("Put member data to classes");
		HashSet<ClassId> processedClassMembers;
		for (size_t i = 0; i < context.newClasses.getSize(); ++i) {
			auto *node = context.newClasses[i];
			auto clazz = compile.classes[node->classId];
			auto classInfo = context.classInfo[clazz->id];
			if (classInfo->genericData || classInfo->member.empty())
				continue;
			if (processedClassMembers.count(clazz->id))
				continue;
			processedClassMembers.insert(clazz->id);
			clazz->memberIdOffset = compile.allMemberId.size();
			for (auto member : classInfo->member) {
				compile.allMemberId.push_back(member->classId);
				compile.allMemberNullable.push_back(member->nullable);
			}
		}

		printDebug("Real Declarations: " +
		           std::to_string(context.declarationNodePool.index +
		                          context.declarationNodePool.vecs.size()));
		printDebug("Real New classes: " +
		           std::to_string(context.newClasses.getSize()));
		printDebug("Real New functions: " +
		           std::to_string(context.newFunctions.getSize()));
		printDebug("Real ClassInfo: " +
		           std::to_string(context.classInfo.size()));
		printDebug("Real FunctionInfo: " +
		           std::to_string(context.functionInfo.size()));

		printDebug("Real Classes: " + std::to_string(compile.classes.size()));
		printDebug("Real Functions: " +
		           std::to_string(compile.functions.size()));
		printDebug("Real ClassMap: " + std::to_string(compile.classMap.size()));
		printDebug("Real FuncMap: " + std::to_string(compile.funcMap.size()));
		// size_t total = 0;
		// for (auto& [k, v] : compile.funcMap)
		// 	++total;

		// printDebug("TOTAL FUNC IN MAP: " + std::to_string(total));
	} catch (const ParserError &err) {
		context.hasError = true;
		context.logError(err.line, err.message, err.hint);
	} catch (const std::exception &err) {
		context.hasError = true;
		std::cerr << "Unexpected exception: " << err.what() << '\n';
	}

	// auto resolveTime = std::chrono::high_resolution_clock::now();
	// std::cerr << "Optimize and Putbytecode time : "
	//           << std::chrono::duration_cast<std::chrono::milliseconds>(
	//                  resolveTime - parserTime)
	//                  .count()
	//           << " ms" << '\n';

	if (context.hasError) {
		state = CompilerState::CT_ERROR;
		return;
	}

	AUTOLANG_PROFILE_MARK("Compile: Bytecodes Generated");
	state = CompilerState::CT_BYTECODE_READY;
}

void ACompiler::run() {
	switch (state) {
		case CompilerState::CT_BYTECODE_READY:
			break;
		case CompilerState::CT_ERROR:
			throw std::logic_error("Compiler is in ERROR state. Call "
			                       "refresh() before running.");

		case CompilerState::CT_READY:
			throw std::logic_error("Bytecode not generated. Call "
			                       "generateBytecodes() before running.");

		case CompilerState::CT_ANALYZED:
			throw std::logic_error(
			    "Source is analyzed but bytecode not generated. "
			    "Call generateBytecodes() before running.");
	}
	AUTOLANG_PROFILE_MARK("Runtime: VM Execution Start");
	vm.start();
	if (exceptionMessage) {
		delete[] exceptionMessage;
	}
	if (vm.callFrames[0]->exception) {
		auto e = vm.callFrames[0]->exception->member->data[0]->str;
		char *str = new char[e->size + 1];
		memcpy(str, e->data, e->size);
		str[e->size] = '\0';
		exceptionMessage = str;
	} else {
		exceptionMessage = nullptr;
	}
	vm.restart();
	AUTOLANG_PROFILE_MARK("Runtime: VM Execution Finished");
}

